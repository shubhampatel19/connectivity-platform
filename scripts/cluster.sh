#!/usr/bin/env bash
# Cluster mode: the cloud side on a local three-node k3d cluster, the edge in
# Docker Compose, joined by the WAN proxy.
#
#   cluster.sh up             create the cluster if needed, deploy, start the edge
#   cluster.sh deploy         rebuild the cloud images from the sibling repos and roll them out
#   cluster.sh edge           (re)start the edge and the WAN against the cluster
#   cluster.sh down           delete the cluster and the edge, with all their data
#   cluster.sh chaos-install  install Chaos Mesh (needs helm)
#   cluster.sh status         nodes, pods, and the image each service runs
#
# Needs docker, k3d (v5.7 or later) and kubectl. Every kubectl call names the
# k3d context explicitly, so other clusters in your kubeconfig are never touched.
set -euo pipefail
cd "$(dirname "$0")/.."

CLUSTER=connectivity
CONTEXT="k3d-$CLUSTER"
NS=connectivity
WORKSPACE=..
CLOUD_SERVICES=(ingest-api telemetry-processor case-service)
CHAOS_MESH_VERSION=2.8.4

k() { kubectl --context "$CONTEXT" -n "$NS" "$@"; }

need() {
  for t in "$@"; do
    command -v "$t" > /dev/null || { echo "$t is required for cluster mode (see the README)" >&2; exit 1; }
  done
}

cluster_exists() { k3d cluster get "$CLUSTER" > /dev/null 2>&1; }

# The image tag for a repo: its commit, plus a hash of local changes when the
# tree is dirty, so every distinct build gets a distinct tag and
# `kubectl rollout undo` always has the previous image to go back to.
image_tag() {
  local dir=$1 tag
  tag=$(git -C "$dir" rev-parse --short=12 HEAD)
  if [ -n "$(git -C "$dir" status --porcelain)" ]; then
    tag="$tag-dirty-$(cd "$dir" && { git diff HEAD; git ls-files -z --others --exclude-standard | xargs -0 -r cat; } | sha256sum | cut -c1-8)"
  fi
  echo "$tag"
}

deploy() {
  need docker k3d kubectl git
  cluster_exists || { echo "no cluster yet: run make cluster-up" >&2; exit 1; }
  local overlay=.deploy images=() dir tag svc w
  mkdir -p "$overlay"
  cat > "$overlay/kustomization.yaml" <<'YAML'
# Generated by scripts/cluster.sh deploy (not committed): the manifests in
# k8s/, with each service pinned to the image built from its repo's commit.
# It lives outside k8s/ because kustomize rejects an overlay inside its base.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../k8s
images:
YAML
  for svc in "${CLOUD_SERVICES[@]}"; do
    dir="$WORKSPACE/connectivity-$svc"
    [ -d "$dir/.git" ] || { echo "$dir is missing: run make bootstrap" >&2; exit 1; }
    tag=$(image_tag "$dir")
    echo "==> build connectivity/$svc:$tag"
    docker build -q -t "connectivity/$svc:$tag" "$dir" > /dev/null
    images+=("connectivity/$svc:$tag")
    printf '  - name: connectivity/%s\n    newTag: "%s"\n' "$svc" "$tag" >> "$overlay/kustomization.yaml"
  done

  echo "==> import images into the cluster's nodes"
  k3d image import --cluster "$CLUSTER" "${images[@]}"

  echo "==> apply manifests"
  # The topic Job is rerun on every deploy (it is idempotent); a finished Job
  # can't be updated in place.
  k delete job kafka-topics --ignore-not-found > /dev/null 2>&1 || true
  # Server-side apply: the dashboards ConfigMap is too big for the
  # last-applied annotation that client-side apply keeps.
  kubectl kustomize --load-restrictor LoadRestrictionsNone "$overlay" \
    | kubectl --context "$CONTEXT" apply --server-side --force-conflicts -f - > /dev/null

  echo "==> wait for every workload to roll out"
  k rollout status statefulset/kafka --timeout=10m
  k wait --for=condition=complete job/kafka-topics --timeout=10m > /dev/null
  for w in $(k get statefulset,deployment -o name); do
    k rollout status "$w" --timeout=10m
  done
}

edge() {
  need docker
  echo "==> start the edge and the WAN (Docker Compose, cloud via host port 8080, spans to Tempo on 4318)"
  WAN_UPSTREAM=host.docker.internal:8080 EDGE_OTLP_ENDPOINT=http://host.docker.internal:4318 \
    COMPOSE_PROFILES='' docker compose up -d --build
}

up() {
  need docker k3d kubectl git
  if [ "$(cat .mode 2> /dev/null)" != cluster ] && [ -n "$(COMPOSE_PROFILES=cloud docker compose ps -q 2> /dev/null)" ]; then
    echo "compose mode is running and uses the same ports; run make down first" >&2
    exit 1
  fi
  if ! cluster_exists; then
    echo "==> create the k3d cluster ($CLUSTER: 1 server, 2 agents)"
    k3d cluster create --config k8s/k3d.yaml
  fi
  echo cluster > .mode
  deploy
  edge
  cat <<TXT

Cluster mode is up. kubectl --context $CONTEXT -n $NS get pods
  Grafana      http://localhost:3000   (Connectivity overview, Connectivity cluster; Explore for Loki and Tempo)
  Prometheus   http://localhost:9090
  Ingest API   http://localhost:8080   (via Traefik; devices go through the WAN proxy)
  Case API     http://localhost:8085   (make cases)
  WAN proxy    http://localhost:8474   (make wan)
Chaos Mesh is optional: make chaos-install
TXT
}

down() {
  need docker k3d
  COMPOSE_PROFILES='' docker compose down -v --remove-orphans || true
  if cluster_exists; then k3d cluster delete "$CLUSTER"; fi
  rm -rf .mode .deploy
}

chaos_install() {
  need helm kubectl
  helm repo add chaos-mesh https://charts.chaos-mesh.org --force-update > /dev/null
  # k3s runs its own containerd, at a socket path the chart can't guess.
  helm upgrade --install chaos-mesh chaos-mesh/chaos-mesh \
    --kube-context "$CONTEXT" --namespace chaos-mesh --create-namespace \
    --version "$CHAOS_MESH_VERSION" \
    --set chaosDaemon.runtime=containerd \
    --set chaosDaemon.socketPath=/run/k3s/containerd/containerd.sock \
    --set controllerManager.replicaCount=1 \
    --set dashboard.securityMode=false \
    --set dashboard.service.nodePort=30233 \
    --set dnsServer.create=false \
    --wait --timeout 10m
  echo "Chaos Mesh is installed: dashboard on http://localhost:2333, experiments with make chaos-ls"
}

status() {
  kubectl --context "$CONTEXT" get nodes -o wide
  echo
  k get pods -o wide
  echo
  k get deployment,statefulset -o custom-columns='NAME:.metadata.name,READY:.status.readyReplicas,WANTED:.spec.replicas,IMAGE:.spec.template.spec.containers[0].image'
}

case "${1:-}" in
  up) up ;;
  deploy) deploy ;;
  edge) edge ;;
  down) down ;;
  chaos-install) chaos_install ;;
  status) status ;;
  *) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
